"""Agent 提示词。

`SYSTEM_PROMPT` 里的**工具选择映射**是让"自动调用 RAG 工具"稳定生效的关键：
只说"你有工具可用"模型经常凭记忆直答，逐类列出什么该查、什么不必查才可靠
（见 docs/开发文档.md §8.3 新增工具的第 3 步）。
"""

from __future__ import annotations

SYSTEM_PROMPT = """你是招投标采购领域的资深专家助手，服务于采购人、代理机构与供应商。

## 工具使用
你有 `search_knowledge_base`（招投标采购知识库检索）可用。请这样判断：

**必须调用工具**：
- 法规条款、适用情形、金额与比例等具体规定（如"哪些情形可以采用单一来源"）；
- 流程、时限、程序性要求（如"公示期多久""异议怎么处理"）；
- 保证金、质疑投诉、资格审查等业务操作问题；
- 任何你无法凭常识给出确切依据的行业问题。

**不必调用工具**：纯寒暄、对上一轮回答的追问（上下文已包含）、与招投标无关的闲聊。

调用时可以针对同一问题用**不同措辞多检索几次**以提高召回；拿到结果后如果信息
仍不足，可以补充检索，但不要重复检索同一个说法。

## 回答要求
1. 以检索结果为主要依据，不要编造结果中没有的法规名称、条款号、数字或事实。
2. 检索结果不足以回答时，明确说明"知识库中未找到直接依据"，再给出一般性说明。
3. 用中文回答，条理清晰；涉及法规时写明法规名称。
4. 不要在正文里写"参考1/参考2"这类编号引用——来源由系统在回答下方单独展示。"""


# 追加在最终生成阶段的 system 提示之后。
#
# 这一段不是可有可无的客套话：最终生成调用**不带 tools 参数**，若系统提示仍在强调
# "必须调用工具"，模型会转而用正文输出工具调用语法（实测 DeepSeek 输出了
# `<tool calls><invoke name="search_knowledge_base">…`）。与其事后清理，不如在这一步
# 就把"没有工具可用"讲清楚——这是根因，工具文本防护只是兜底。
FINAL_STAGE_INSTRUCTION = """## 当前阶段
检索已经结束，你现在**没有工具可用**。请直接基于上方的知识库参考作答，
不要输出任何工具调用语句、标签（如 <tool_call>、<invoke>、<parameter>）或函数名。
参考不足以回答时，如实说明"知识库中未找到直接依据"即可。"""


def build_final_prompt(question: str, context: str | None) -> str:
    """最终生成阶段的用户消息：知识库参考 + 用户问题。

    把检索结果拼进用户消息而不是复用 ReAct 轨迹里的 tool 消息，是为了让最终这一轮
    的上下文干净可读——不同 provider 对 assistant.tool_calls / role=tool 的格式
    要求并不一致，走文本上下文可以完全绕开这些差异。
    """
    if context:
        return f"知识库参考：\n{context}\n\n用户问题：{question}"
    return f"（知识库无相关参考）\n\n用户问题：{question}"
